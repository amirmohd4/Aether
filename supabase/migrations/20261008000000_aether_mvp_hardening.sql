alter table aether_internal.aether_v2_execution_events enable row level security;
alter table aether_internal.aether_v2_task_queue enable row level security;
alter table aether_internal.aether_v2_task_checkpoints enable row level security;
alter table aether_internal.aether_v2_case_leases enable row level security;
alter table aether_internal.aether_v2_documents enable row level security;
alter table aether_internal.aether_v2_notifications enable row level security;
alter table aether_internal.aether_v2_payments enable row level security;
alter table aether_internal.aether_v2_api_keys enable row level security;
alter table aether_internal.aether_v2_usage enable row level security;

revoke all on schema aether_internal from anon, authenticated;
revoke all on all tables in schema aether_internal from anon, authenticated;

alter table public.aether_memberships enable row level security;
revoke all on public.aether_memberships from anon, authenticated;
grant select on public.aether_memberships to authenticated;

drop policy if exists "members can read their own membership" on public.aether_memberships;
create policy "members can read their own membership"
  on public.aether_memberships
  for select to authenticated
  using (user_id = (select auth.uid()));

create or replace function public.handle_aether_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.aether_memberships (user_id, tenant_id, role, status)
  values (new.id, 'user:' || new.id::text, 'user', 'active')
  on conflict (user_id, tenant_id) do nothing;
  return new;
end;
$$;

revoke all on function public.handle_aether_new_user() from public;
revoke all on function public.handle_aether_new_user() from anon, authenticated;

drop trigger if exists on_aether_auth_user_created on auth.users;
create trigger on_aether_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_aether_new_user();

-- Lock legacy public application tables until migrated behind the Aether API.
DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'citizens',
    'api_keys',
    'properties',
    'certificates',
    'workflow_states',
    'fraud_detection_logs',
    'trade_licenses',
    'building_permits',
    'water_connections',
    'birth_certificates',
    'death_certificates',
    'medical_licenses'
  ]
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format(
      'DROP POLICY IF EXISTS "%s deny browser access" ON public.%I',
      table_name, table_name
    );
    EXECUTE format(
      'CREATE POLICY "%s deny browser access" ON public.%I
       FOR ALL TO anon, authenticated
       USING (false)
       WITH CHECK (false)',
      table_name, table_name
    );
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated', table_name);
  END LOOP;
END
$$;
