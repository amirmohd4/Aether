-- Aether MVP schema hardening for installations that already ran the first
-- private-persistence migration. This migration is idempotent and upgrades
-- existing V2 tables before enabling the production authorization boundary.

create schema if not exists aether_internal;

-- Existing installations may already have aether_v2_cases from the first MVP
-- migration with only the original columns.
alter table if exists aether_internal.aether_v2_cases
  add column if not exists owner_user_id varchar(128);
alter table if exists aether_internal.aether_v2_cases
  add column if not exists tenant_id varchar(128);
alter table if exists aether_internal.aether_v2_cases
  add column if not exists service_id varchar(128);

create index if not exists idx_aether_v2_cases_owner_user_id
  on aether_internal.aether_v2_cases(owner_user_id);
create index if not exists idx_aether_v2_cases_tenant_id
  on aether_internal.aether_v2_cases(tenant_id);
create index if not exists idx_aether_v2_cases_service_id
  on aether_internal.aether_v2_cases(service_id);

alter table if exists aether_internal.aether_v2_execution_events
  add column if not exists tenant_id varchar(128);
alter table if exists aether_internal.aether_v2_execution_events
  add column if not exists previous_hash varchar(128);
alter table if exists aether_internal.aether_v2_execution_events
  add column if not exists event_hash varchar(128);
alter table if exists aether_internal.aether_v2_execution_events
  add column if not exists sequence integer;

create index if not exists idx_aether_v2_events_tenant_id
  on aether_internal.aether_v2_execution_events(tenant_id);
create index if not exists idx_aether_v2_events_event_hash
  on aether_internal.aether_v2_execution_events(event_hash);

-- Unique only for assigned per-case sequence values. Existing legacy rows may
