-- Add durable internal administrative action and work-item tables.
-- These tables are server-only; the runtime role receives table-level access
-- through RLS policies and explicit grants, never schema CREATE privileges.

create table if not exists aether_internal.aether_v2_admin_actions (
  id bigint generated by default as identity primary key,
  action_id varchar(64) not null unique,
  tenant_id varchar(128) not null,
  case_id varchar(64) not null,
  action_type varchar(128) not null,
  status varchar(32) not null,
  priority varchar(16) not null default 'normal',
  idempotency_key varchar(256) not null,
  payload jsonb not null default '{}'::jsonb,
  outcome jsonb,
  attempts integer not null default 0,
  available_at timestamptz not null,
  locked_by varchar(128),
  lease_until timestamptz,
  last_error text,
  requested_by varchar(128) not null,
  approved_by varchar(128),
  approved_at timestamptz,
  created_at timestamptz not null,
  updated_at timestamptz not null,
  verified_at timestamptz,
  constraint uq_aether_admin_action_tenant_key unique (tenant_id, idempotency_key)
);

create index if not exists idx_aether_admin_actions_tenant
  on aether_internal.aether_v2_admin_actions(tenant_id);
create index if not exists idx_aether_admin_actions_case
  on aether_internal.aether_v2_admin_actions(case_id);
create index if not exists idx_aether_admin_actions_type
  on aether_internal.aether_v2_admin_actions(action_type);
create index if not exists idx_aether_admin_actions_status
  on aether_internal.aether_v2_admin_actions(status);
create index if not exists idx_aether_admin_actions_available_at
  on aether_internal.aether_v2_admin_actions(available_at);
create index if not exists idx_aether_admin_actions_locked_by
  on aether_internal.aether_v2_admin_actions(locked_by);
create index if not exists idx_aether_admin_actions_lease_until
  on aether_internal.aether_v2_admin_actions(lease_until);

create table if not exists aether_internal.aether_v2_admin_work_items (
  id bigint generated by default as identity primary key,
  work_item_id varchar(64) not null unique,
  tenant_id varchar(128) not null,
  case_id varchar(64) not null,
  source_action_id varchar(64) not null,
  idempotency_key varchar(256) not null,
  title varchar(512) not null,
  department varchar(128) not null default 'unassigned',
  priority varchar(16) not null default 'normal',
  status varchar(32) not null default 'open',
  required_evidence jsonb not null default '[]'::jsonb,
  details jsonb not null default '{}'::jsonb,
  assigned_to varchar(128),
  created_at timestamptz not null,
  updated_at timestamptz not null,
  completed_at timestamptz,
  completion_evidence jsonb not null default '[]'::jsonb,
  constraint uq_aether_admin_work_item_tenant_key unique (tenant_id, idempotency_key)
);

create index if not exists idx_aether_admin_work_items_tenant
  on aether_internal.aether_v2_admin_work_items(tenant_id);
create index if not exists idx_aether_admin_work_items_case
  on aether_internal.aether_v2_admin_work_items(case_id);
create index if not exists idx_aether_admin_work_items_source_action
  on aether_internal.aether_v2_admin_work_items(source_action_id);
create index if not exists idx_aether_admin_work_items_status
  on aether_internal.aether_v2_admin_work_items(status);
create index if not exists idx_aether_admin_work_items_assigned_to
  on aether_internal.aether_v2_admin_work_items(assigned_to);

alter table aether_internal.aether_v2_admin_actions enable row level security;
alter table aether_internal.aether_v2_admin_work_items enable row level security;

revoke all on table aether_internal.aether_v2_admin_actions from public, anon, authenticated;
revoke all on table aether_internal.aether_v2_admin_work_items from public, anon, authenticated;

grant select, insert, update, delete
  on table aether_internal.aether_v2_admin_actions to aether_runtime;
grant select, insert, update, delete
  on table aether_internal.aether_v2_admin_work_items to aether_runtime;

grant usage, select, update
  on sequence aether_internal.aether_v2_admin_actions_id_seq to aether_runtime;
grant usage, select, update
  on sequence aether_internal.aether_v2_admin_work_items_id_seq to aether_runtime;

drop policy if exists aether_runtime_full_access
  on aether_internal.aether_v2_admin_actions;
create policy aether_runtime_full_access
  on aether_internal.aether_v2_admin_actions
  for all to aether_runtime
  using (true)
  with check (true);

drop policy if exists aether_runtime_full_access
  on aether_internal.aether_v2_admin_work_items;
create policy aether_runtime_full_access
  on aether_internal.aether_v2_admin_work_items
  for all to aether_runtime
  using (true)
  with check (true);
